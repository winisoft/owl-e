package com.wini.owle.ksp.writer

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.wini.owle.ksp.utils.ConstraintExtractor
import java.io.OutputStreamWriter


class ValidatorFileGenerator(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger
) {

    fun generateValidator(modelClass: KSClassDeclaration) {
        val packageName = modelClass.packageName.asString()
        val className = modelClass.simpleName.asString()
        val validatorPackage = packageName.replace(".dto.", ".validators.")
        val validatorName = "${className}Validator"

        val file = codeGenerator.createNewFile(
            Dependencies(false, modelClass.containingFile!!),
            validatorPackage,
            validatorName,
            "kt"
        )

        OutputStreamWriter(file).use { writer ->
            writer.write(
                buildString {
                    appendLine("package $validatorPackage")
                    appendLine()
                    appendLine("import com.wini.owle.error.ConstraintError")
                    appendLine("import com.wini.owle.validators.DtoValidator")
                    appendLine("import $packageName.$className")
                    appendLine("import kotlin.reflect.KProperty1")
                    appendLine("import com.wini.owle.error.*")
                    appendLine()
                    appendLine("/**")
                    appendLine(" * Validator for $className")
                    appendLine(" * Generated by ValidatorGeneratorProcessor")
                    appendLine(" */")
                    appendLine("class $validatorName : DtoValidator<$className> {")
                    appendLine("    override fun fieldValidations(dto: $className): List<ConstraintError> {")
                    appendLine("        return buildList {")

                    addPropertyConstraints(modelClass, className, logger)
                        .forEach { appendLine("            $it") }

                    addMultiFieldConstraints(modelClass, className, logger)
                        .forEach { appendLine("            $it") }

                    appendLine("        }")
                    appendLine("    }")
                    appendLine("}")
                }
            )
        }

        logger.info("Generated validator: $validatorPackage.$validatorName")
    }

    private fun addPropertyConstraints(
        modelClass: KSClassDeclaration,
        className: String,
        logger: KSPLogger
    ): List<String> {
        logger.info("Adding property constraints for $className")
        return modelClass.getAllProperties().flatMap { property ->
            ConstraintExtractor.propertyExtract(property, className, logger)
        }.toList()
    }


    private fun addMultiFieldConstraints(
        modelClass: KSClassDeclaration,
        className: String,
        logger: KSPLogger
    ): List<String> {
        return ConstraintExtractor.multiFieldExtract(modelClass, className, logger)
    }
}
