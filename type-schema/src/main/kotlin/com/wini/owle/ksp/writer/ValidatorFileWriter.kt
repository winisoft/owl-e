package com.wini.owle.ksp.writer

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSType
import com.wini.owle.ksp.utils.ConstraintExtractor
import com.wini.owle.ksp.utils.ext.findByFqm
import com.wini.owle.ksp.utils.ext.findByFqns
import com.wini.owle.schema.wrapper.declaration.error.ErrorDeclaration
import com.wini.owle.schema.wrapper.declaration.ModelDeclaration
import com.wini.owle.schema.wrapper.declaration.ConstrainedField
import java.io.OutputStreamWriter


class ValidatorFileWriter(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
    private val errors: List<ErrorDeclaration>,
    private val models: List<ModelDeclaration>
) {

    fun generateValidator(modelClass: ModelDeclaration) {
        val packageName = modelClass.packageName.asString()
        val className = modelClass.simpleName.asString()
        val validatorPackage = packageName.replace(".dto.", ".validators.")
        val validatorName = "${className}Validator"

        val modelFqns: Set<String> = models.map { it.qualifiedName?.asString() ?: it.fqName }.toSet()

        data class Dep(
            val variableName: String,
            val modelDeclaration: ModelDeclaration
        )

        val deps = mutableMapOf<String, Dep>()
        val nestedValidationLines = mutableListOf<String>()
        val additionalImports = mutableSetOf<String>()

        modelClass.getAllProperties().forEach { prop ->
            val propType = prop.type.resolve()
            val propName = prop.simpleName.asString()
            val (targetModel, isList) = findTargetModel(propType, modelFqns)
            if (targetModel != null) {
                val depClassName = targetModel.simpleName.asString()
                val depVarName = "${depClassName.replaceFirstChar { it.lowercaseChar() }}Validator"

                deps.computeIfAbsent(targetModel.fqName) {
                    additionalImports.add("import ${targetModel.packageName.asString()}.$depClassName")
                    // the collaborator is now the concrete validator, which usually lives in a
                    // different package than this one
                    additionalImports.add(
                        "import ${targetModel.packageName.asString().replace(".dto.", ".validators.")}.${depClassName}Validator"
                    )
                    Dep(depVarName, targetModel)
                }

                val nullableOpener = if (propType.isMarkedNullable) "dto.$propName?.let { " else ""
                val nullableCloser = if (propType.isMarkedNullable) " }" else ""
                val validationCall = if (isList) {
                    "$depVarName().validateAll(dto.$propName).violations"
                } else {
                    "$depVarName().validate(dto.$propName).violations"
                }
                nestedValidationLines.add(
                    if (propType.isMarkedNullable) {
                        "$nullableOpener addAll($validationCall)$nullableCloser"
                    } else {
                        "addAll($validationCall)"
                    }
                )
            }
        }

        val constructorParams = deps.values.joinToString(",\n") { dep ->
            "    private val ${dep.variableName}: () -> ${dep.modelDeclaration.simpleName.asString()}Validator"
        }

        val file = codeGenerator.createNewFile(
            Dependencies(false, modelClass.containingFile!!),
            validatorPackage,
            validatorName,
            "kt"
        )

        OutputStreamWriter(file).use { writer ->
            writer.write(
                buildString {
                    appendLine("package $validatorPackage")
                    appendLine()
                    appendLine("import com.wini.owle.error.ConstraintError")
                    appendLine("import com.wini.owle.validators.DtoValidator")
                    appendLine("import $packageName.$className")
                    appendLine("import com.wini.owle.error.*")
                    additionalImports.sorted().forEach { if (it != "import $packageName.$className") appendLine(it) }
                    appendLine()
                    appendLine("/**")
                    appendLine(" * Validator for $className")
                    appendLine(" * Generated by ValidatorGeneratorProcessor")
                    appendLine(" */")
                    if (deps.isNotEmpty()) {
                        appendLine("class $validatorName(")
                        appendLine(constructorParams)
                        appendLine(") : DtoValidator<$className> {")
                    } else {
                        appendLine("class $validatorName : DtoValidator<$className> {")
                    }

                    appendLine("    override fun fieldValidations(dto: $className): List<ConstraintError> {")
                    appendLine("        return buildList {")

                    addPropertyConstraints(modelClass, errors, className, logger).forEach {
                        appendLine("            $it")
                    }

                    addMultiFieldConstraints(modelClass, className, logger).forEach {
                        appendLine("            $it")
                    }

                    nestedValidationLines.forEach { line ->
                        appendLine("            $line")
                    }

                    appendLine("        }")
                    appendLine("    }")
                    appendLine("}")
                }
            )
        }

        logger.info("Generated validator: $validatorPackage.$validatorName")
    }

    private fun addPropertyConstraints(
        modelClass: ModelDeclaration,
        errors: List<ErrorDeclaration>,
        className: String,
        logger: KSPLogger
    ): List<String> {
        logger.info("Adding property constraints for $className")
        return modelClass.constrainedFields.flatMap { (prop, constraints) ->
            ConstraintExtractor.propertyExtract(
                prop,
                constraints,
                className,
                logger,
                errors
            )
        }
    }


    private fun addMultiFieldConstraints(
        modelClass: ModelDeclaration,
        className: String,
        logger: KSPLogger
    ): List<String> {
        return ConstraintExtractor.multiFieldExtract(modelClass, className, logger)
    }

    private fun findTargetModel(type: KSType, modelFqns: Set<String>): Pair<ModelDeclaration?, Boolean> {
        val typeFqn = type.declaration.qualifiedName?.asString()
        if (typeFqn != null && typeFqn in modelFqns) {
            val target = models.first { it.fqName == typeFqn || it.qualifiedName?.asString() == typeFqn }
            return target to false
        }
        if (typeFqn == "kotlin.collections.List" || typeFqn == "kotlin.collections.MutableList" || typeFqn == "java.util.List") {
            val argType = type.arguments.firstOrNull()?.type?.resolve()
            val argFqn = argType?.declaration?.qualifiedName?.asString()
            if (argFqn != null && argFqn in modelFqns) {
                val target = models.first { it.fqName == argFqn || it.qualifiedName?.asString() == argFqn }
                return target to true
            }
        }
        return null to false
    }
}
