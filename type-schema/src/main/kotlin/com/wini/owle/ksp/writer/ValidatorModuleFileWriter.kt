package com.wini.owle.ksp.writer

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.wini.owle.ksp.utils.ext.isValidatorGenTarget
import java.io.OutputStreamWriter


class ValidatorModuleFileWriter(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger
) {

    val validatorsPackage = "com.wini.owle.validators"
    val importStatements = mutableSetOf<String>()
    val provideDeclaration = mutableSetOf<String>()

    fun generate(modelClasses: List<KSClassDeclaration>) {

        val file = codeGenerator.createNewFile(
            Dependencies(false),
            "com.wini.owle.validators",
            "Module",
            "kt"
        )

        modelClasses.filter { it.isValidatorGenTarget }.forEach {
            val packageName = it.packageName.asString()
            val className = it.simpleName.asString()

            importStatements.add("import $packageName.*")
            importStatements.add("import ${packageName.replace(".dto.", ".validators.")}.*")

            provideDeclaration.add("single<DtoValidator<$className>> { ${className}Validator() }")
        }

        OutputStreamWriter(file).use { writer ->
            writer.write(
                buildString {
                    appendLine("package $validatorsPackage")
                    appendLine()
                    importStatements.sorted().forEach {
                        appendLine(it)
                    }
                    appendLine("import com.wini.owle.validators.DtoValidator")
                    appendLine("import org.koin.dsl.module")
                    appendLine()
                    appendLine("/**")
                    appendLine(" * koin module definition providing Validator types")
                    appendLine(" * Generated by ValidatorGeneratorProcessor")
                    appendLine(" */")
                    appendLine("val validatorsModule = module {")
                    provideDeclaration.forEach {
                        appendLine("    $it")
                    }
                    appendLine("}")
                }
            )
        }

        logger.info("Generated Koin Module: com.wini.owle.validators.Module")
    }

}